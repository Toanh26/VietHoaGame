"""Chạy:  python -m unittest discover -s tests"""
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def run(*args, cwd):
    r = subprocess.run([sys.executable, "-m", "vntrans", *args], cwd=cwd, capture_output=True, text=True,
                       encoding="utf-8", env={**os.environ, "PYTHONPATH": str(ROOT)})
    assert r.returncode == 0, r.stdout + r.stderr
    return r.stdout


def make_game(d: Path):
    data = d / "rpg" / "www" / "data"
    data.mkdir(parents=True)
    (data / "Actors.json").write_text(json.dumps([None, {"id": 1, "name": "Harold", "nickname": "", "profile": "A brave knight."}]), encoding="utf-8")
    (data / "Items.json").write_text(json.dumps([None, {"id": 1, "name": "Potion", "description": "Restores 50 HP."}]), encoding="utf-8")
    (data / "System.json").write_text(json.dumps({"gameTitle": "My Quest", "currencyUnit": "G", "elements": ["", "Fire"],
        "terms": {"basic": ["Level"], "commands": ["Fight", None], "params": ["Max HP"],
                  "messages": {"victory": "%1 was victorious!"}}}))
    ev_list = [
        {"code": 101, "indent": 0, "parameters": ["", 0, 0, 2, "Harold"]},
        {"code": 401, "indent": 0, "parameters": ["Hello \\C[2]\\N[1]\\C[0]!"]},
        {"code": 401, "indent": 0, "parameters": ["Welcome to the village."]},
        {"code": 102, "indent": 0, "parameters": [["Yes", "No"], 1, 0, 2, 0]},
        {"code": 402, "indent": 0, "parameters": [0, "Yes"]},
        {"code": 401, "indent": 1, "parameters": ["Great."]},
        {"code": 0, "indent": 1, "parameters": []},
        {"code": 0, "indent": 0, "parameters": []},
    ]
    (data / "Map001.json").write_text(json.dumps({"displayName": "Village", "events": [None,
        {"id": 1, "name": "EV001", "pages": [{"list": ev_list}]}]}))
    (data / "CommonEvents.json").write_text(json.dumps([None]), encoding="utf-8")

    tl = d / "renpy" / "game" / "tl" / "vietnamese"
    tl.mkdir(parents=True)
    (tl / "script.rpy").write_text(
        '# game/script.rpy:10\ntranslate vietnamese start_abc:\n\n    # e "Hello, [player]! {b}Nice{/b} to \\"meet\\" you."\n'
        '    e "Hello, [player]! {b}Nice{/b} to \\"meet\\" you."\n\n'
        'translate vietnamese strings:\n\n    # game/screens.rpy:5\n    old "Start"\n    new "Start"\n')

    (d / "godot").mkdir()
    (d / "godot" / "vi.po").write_text(
        'msgid ""\nmsgstr ""\n"Language: en\\n"\n"Plural-Forms: nplurals=2; plural=(n != 1);\\n"\n\n'
        'msgctxt "menu"\nmsgid "New Game"\nmsgstr ""\n\n'
        'msgid "You have %d coin"\nmsgid_plural "You have %d coins"\nmsgstr[0] ""\nmsgstr[1] ""\n\n'
        'msgid ""\n"Line one\\n"\n"Line two"\nmsgstr ""\n')

    x = d / "unity" / "BepInEx" / "Translation" / "vi" / "Text"
    x.mkdir(parents=True)
    (x / "_AutoGeneratedTranslations.txt").write_text("// comment\nStart Game=\nHP\\=100=HP\\=100\nDone=Xong\n", encoding="utf-8")

    (d / "csv").mkdir()
    (d / "csv" / "text.csv").write_text('keys,en,ja\nGREET,"Hello, friend",こんにちは\nBYE,Goodbye,さようなら\n', encoding="utf-8")


class RoundTrip(unittest.TestCase):
    def test_all(self):
        with tempfile.TemporaryDirectory() as t:
            t = Path(t)
            make_game(t)
            for name, extra in [("rpg", []), ("renpy", []), ("godot", []), ("unity", []),
                                ("csv", ["--adapter", "csv"])]:
                proj = str(t / f"{name}.json")
                run("-p", proj, "extract", str(t / name), *extra, cwd=t)
                run("-p", proj, "translate", "--engine", "dummy", cwd=t)
                run("-p", proj, "apply", "-o", str(t / f"{name}_vi"), cwd=t)

            m = json.loads((t / "rpg_vi/www/data/Map001.json").read_text(encoding="utf-8"))
            lst = m["events"][1]["pages"][0]["list"]
            self.assertEqual(lst[1]["parameters"][0], "[VI] Hello \\C[2]\\N[1]\\C[0]!")
            self.assertEqual(lst[2]["parameters"][0], "Welcome to the village.")  # cùng khung với dòng trên
            self.assertEqual(lst[3]["parameters"][0], ["[VI] Yes", "[VI] No"])
            self.assertEqual(lst[5], {"code": 401, "indent": 1, "parameters": ["[VI] Great."]})
            self.assertEqual(lst[0]["parameters"][4], "[VI] Harold")
            sysj = json.loads((t / "rpg_vi/www/data/System.json").read_text(encoding="utf-8"))
            self.assertEqual(sysj["terms"]["messages"]["victory"], "[VI] %1 was victorious!")
            self.assertIsNone(sysj["terms"]["commands"][1])

            rp = (t / "renpy_vi/game/tl/vietnamese/script.rpy").read_text(encoding="utf-8")
            self.assertIn('    e "[VI] Hello, [player]! {b}Nice{/b} to \\"meet\\" you."', rp)
            self.assertIn('    # e "Hello', rp)
            self.assertIn('new "[VI] Start"', rp)

            po = (t / "godot_vi/vi.po").read_text(encoding="utf-8")
            self.assertIn('msgstr "[VI] New Game"', po)
            self.assertIn('msgstr[0] "[VI] You have %d coins"', po)
            self.assertNotIn("msgstr[1]", po)
            self.assertIn('msgstr "[VI] Line one\\nLine two"', po)
            self.assertIn("nplurals=1", po)

            xu = (t / "unity_vi/BepInEx/Translation/vi/Text/_AutoGeneratedTranslations.txt").read_text(encoding="utf-8")
            self.assertIn("Start Game=[VI] Start Game\n", xu)
            self.assertIn("HP\\=100=[VI] HP\\=100\n", xu)
            self.assertIn("Done=Xong", xu)

            cs = (t / "csv_vi/text.csv").read_text(encoding="utf-8")
            self.assertIn('keys,en,ja,vi', cs)
            self.assertIn('"[VI] Hello, friend"', cs)

    def test_placeholders(self):
        from vntrans.placeholders import check, protect, restore
        m, toks = protect("Hi \\C[2]\\N[1]\\C[0], you got %d {b}gold{/b} [name]!")
        self.assertEqual(len(toks), 7)
        self.assertNotIn("\\", m)
        self.assertEqual(restore(m, toks), "Hi \\C[2]\\N[1]\\C[0], you got %d {b}gold{/b} [name]!")
        self.assertTrue(check("⟦0⟧ only", toks))

    def test_wrap_and_csv(self):
        from vntrans.adapters.rpgmaker import RpgMakerAdapter
        lines = RpgMakerAdapter._wrap("\\C[2]Xin chào\\C[0] các bạn đã đến với ngôi làng nhỏ bé này", 20)
        self.assertGreater(len(lines), 1)
        self.assertTrue(all(len(l.replace("\\C[2]", "").replace("\\C[0]", "")) <= 20 for l in lines))


if __name__ == "__main__":
    unittest.main()
